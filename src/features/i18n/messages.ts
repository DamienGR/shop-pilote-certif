/**
 * Every string the core renders, in French: the storefront's below, and the
 * Admin's spread in at the end from `admin/` (one fragment per Admin section).
 *
 * ONE flat object with dotted keys, not nested groups. The key is the thing a
 * call site writes and a reviewer greps for; nesting would make `t()` walk a
 * path at runtime and turn a missing string into `undefined` at render instead
 * of a red squiggle in the editor.
 *
 * `satisfies Catalog` is the whole compile-time story: `MessageKey` is derived
 * FROM this object, so `t('produit.inexistant')` does not compile, and a second
 * locale — declared `const en: Catalog` — cannot omit a key. The reference
 * catalog and the type are the same file on purpose; two hand-written lists
 * eventually disagree, and the one the compiler believes is not the one the
 * translator edited.
 *
 * Placeholders are `{nom}` and are substituted by `t()`. They are named, never
 * positional: French word order is not English word order, and a translator
 * moving `{count}` past `{total}` must not silently swap two numbers.
 *
 * Typography is French typography: `’` for the apostrophe, `…` for the
 * ellipsis, and a NARROW NO-BREAK SPACE (U+202F) before `?`, `!`, `;` and `:`
 * — the same character `Intl.NumberFormat('fr-FR')` puts in `1 234,56 €`.
 * `messages.test.ts` enforces it, because a plain space there is a line break
 * waiting to happen on a narrow screen.
 */
